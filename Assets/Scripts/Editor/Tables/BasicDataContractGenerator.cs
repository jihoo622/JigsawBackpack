using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

public static class BasicDataContractGenerator
{
    const string OUTPUT_PATH = "Assets/Scripts/Runtime/Data/BasicDataContract.cs";

    [MenuItem("Tools/MyJG/Tables/Generate Basic Data Contract")]
    public static void Generate()
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode)
        {
            Debug.LogWarning("기초데이터 계약 생성은 플레이 종료 후 실행하세요.");
            return;
        }
        var data = TableManager.ReadSourceForAuthoring<BasicDataTableData>();
        string content = Build(data);
        if (!File.Exists(OUTPUT_PATH) || File.ReadAllText(OUTPUT_PATH) != content)
        {
            File.WriteAllText(OUTPUT_PATH, content, new UTF8Encoding(false));
            AssetDatabase.Refresh();
        }
    }

    static string Build(BasicDataTableData _data)
    {
        var numbers = Scoped(_data, _group => _group.numbers, _row => _row.id);
        var texts = Scoped(_data, _group => _group.texts, _row => _row.id);
        var colors = Scoped(_data, _group => _group.colors, _row => _row.id);
        var result = new StringBuilder();
        result.AppendLine("// Generated by BasicDataContractGenerator. Do not edit by hand.");
        result.AppendLine("public static class BasicDataContract");
        result.AppendLine("{");
        WriteKeys(result, "Numbers", numbers.Keys);
        WriteKeys(result, "Texts", texts.Keys);
        WriteKeys(result, "Colors", colors.Keys);
        result.AppendLine("    public static readonly System.Collections.Generic.Dictionary<string, int> TextArgumentCounts =");
        result.AppendLine("        new System.Collections.Generic.Dictionary<string, int>");
        result.AppendLine("        {");
        foreach (var pair in texts)
        {
            result.Append("            { ").Append('"').Append(pair.Key).Append('"')
                .Append(", ").Append(pair.Value.arguments).AppendLine(" },");
        }
        result.AppendLine("        };");
        result.AppendLine("}");
        return result.ToString();
    }

    static void WriteKeys(StringBuilder _output, string _name, IEnumerable<string> _keys)
    {
        _output.Append("    public static readonly string[] ").Append(_name).AppendLine(" =");
        _output.AppendLine("    {");
        foreach (string key in _keys)
        {
            _output.Append("        ").Append('"').Append(key).Append('"').AppendLine(",");
        }
        _output.AppendLine("    };");
    }

    static SortedDictionary<string, T> Scoped<T>(BasicDataTableData _data,
        Func<BasicDataGroupData, T[]> _rows, Func<T, string> _id) where T : class
    {
        var result = new SortedDictionary<string, T>(StringComparer.Ordinal);
        var groups = new HashSet<string>(StringComparer.Ordinal);
        foreach (var group in _data.groups ?? Array.Empty<BasicDataGroupData>())
        {
            if (group == null || !ValidKey(group.id) || !groups.Add(group.id))
            {
                throw new InvalidOperationException("기초데이터 그룹 ID가 잘못되었거나 중복되었습니다.");
            }
            var localKeys = new HashSet<string>(StringComparer.Ordinal);
            foreach (var row in _rows(group) ?? Array.Empty<T>())
            {
                if (row == null || !ValidKey(_id(row)) || !localKeys.Add(_id(row)) ||
                    !result.TryAdd(group.id + "." + _id(row), row))
                {
                    throw new InvalidOperationException("기초데이터 항목 ID가 잘못되었거나 중복되었습니다: " + group.id);
                }
            }
        }
        return result;
    }

    static bool ValidKey(string _id)
    {
        return !string.IsNullOrWhiteSpace(_id) && _id.All(_character =>
            char.IsLetterOrDigit(_character) || _character == '.' || _character == '_');
    }
}
